const seedAbilities = async () => {
	try {
		console.log('Preparing to seed abilities...')
		const operations = abilitiesData.map(ability => ({
			updateOne: {
				filter: { name: ability.name },
				update: { $set: ability },
				upsert: true
			}
		}))
		const result = await Ability.bulkWrite(operations)
		console.log('✅ Abilities seeded successfully!')
		console.log(`   - Matched: ${result.matchedCount}`)
		console.log(`   - Modified: ${result.modifiedCount}`)
		console.log(`   - Upserted: ${result.upsertedCount}`)
	} catch (error) {
		console.error('❌ Error seeding abilities:', error)
	}
}

