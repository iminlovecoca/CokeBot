const seedDatabase = async () => {
	try {
		await mongoose.connect(process.env.MONGO_URL)
		console.log('✅ Database connected successfully for seeding.')

		console.log('Upserting species data...')
		for (const species of speciesData) {
			await Species.findOneAndUpdate(
				{ name: species.name },
				species,
				{ upsert: true }
			)
		}
		console.log('✅ Species data has been successfully synced.')

		console.log('Linking evolutions...')
		const speciesMap = new Map()
		const allSpecies = await Species.find({})
		allSpecies.forEach(s => speciesMap.set(s.name, s._id))

		for (const [fromData, evolutionData] of Object.entries(evolutionChains)) {
			const fromId = speciesMap.get(fromData)
			if (!fromId) continue

			const evolutions = Array.isArray(evolutionData.evolves_to) ? evolutionData.evolves_to : [evolutionData]
			const evolutionPaths = []

			for (const evo of evolutions) {
				const toId = speciesMap.get(evo.species_name || evo.evolves_to);
				if (toId) {
					// Build the evolution path object for the database
					evolutionPaths.push({
						species_id: toId,
						method: evo.method || 'level',
						level: evo.at_level,
						item_id: evo.item_id
					})
					// Update the evolved form with its pre-evolution
					await Species.findByIdAndUpdate(toId, { $set: { preevolution_species_id: fromId } })
				}
			}

			// Update the base form with all its possible evolution paths
			if (evolutionPaths.length > 0) {
				await Species.findByIdAndUpdate(fromId, { $set: { evolution: evolutionPaths } })
			}
		}

		console.log('Upserting item data...')
		for (const item of itemsData) {
			await Item.findOneAndUpdate({ item_id: item.item_id }, item, { upsert: true })
		}
		console.log('✅ Item data has been successfully synced.')

		console.log('✅ Database has been successfully seeded and evolutions linked!')
	} catch (error) {
		console.error('❌ Error seeding the database:', error)
	} finally {
		await mongoose.disconnect()
		console.log('✅ Database disconnected.')
	}
}

seedDatabase()
